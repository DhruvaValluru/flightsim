#!/usr/bin/env python3
"""Generate the CC0 show LUTs (aces2-display): assets/looks/*.cube + looks.json.

Deterministic: the same numbers on every run and platform (float64, six
decimals), so tests/test_display.py regenerates them and compares sha256.
Both LUTs are authored here from closed-form curves, so they are the
project's own work, dedicated CC0-1.0.

They are applied on ACEScct code values (core/capture/display.py
LUT_SPACE) of the linear frame before the ACES 2.0 SDR view:

  warm_print         a warm print stock: +4 % red / -7 % blue on linear
                     light, 1.08 log contrast about 18 % grey, highlight
                     saturation rolled off toward luminance.
  broadcast_neutral  a near-neutral broadcast trim: 0.92 saturation and
                     1.03 log contrast about 18 % grey, no colour shift.

Usage: python scripts/make_show_luts.py [--out assets/looks]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Callable, Dict

import numpy as np

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "assets" / "looks"
SIZE = 33
LICENCE = "CC0-1.0"
SPACE = "ACEScct"

# ACEScct (S-2016-001), the constants as published.
_CUT_LIN = 0.0078125
_A = 10.5402377416545
_B = 0.0729055341958355
_CUT_CCT = 0.155251141552511


def acescct_decode(c: np.ndarray) -> np.ndarray:
    return np.where(c <= _CUT_CCT, (c - _B) / _A, np.power(2.0, c * 17.52 - 9.72))


def acescct_encode(x: np.ndarray) -> np.ndarray:
    safe = np.maximum(x, _CUT_LIN)
    return np.where(x <= _CUT_LIN, _A * x + _B, (np.log2(safe) + 9.72) / 17.52)


#: AP1 luminance weights (ACEScg; the frame is in ACEScct/AP1 once the
#: display step has converted it).
_LUMA = np.array([0.2722287168, 0.6740817658, 0.0536895174])
_GREY_CCT = float(acescct_encode(np.array(0.18)))


def _contrast(c: np.ndarray, k: float) -> np.ndarray:
    return _GREY_CCT + k * (c - _GREY_CCT)


def warm_print(c: np.ndarray) -> np.ndarray:
    c = _contrast(c, 1.08)
    lin = np.maximum(acescct_decode(c), 0.0) * np.array([1.04, 1.0, 0.93])
    y = lin @ _LUMA
    # Saturation 1.0 at grey and below, 0.8 by 16x grey (log2 4 stops up).
    stops = np.clip(np.log2(np.maximum(y, 1e-10) / 0.18) / 4.0, 0.0, 1.0)
    sat = 1.0 - 0.2 * stops
    lin = y[..., None] + sat[..., None] * (lin - y[..., None])
    return acescct_encode(np.maximum(lin, 0.0))


def broadcast_neutral(c: np.ndarray) -> np.ndarray:
    c = _contrast(c, 1.03)
    lin = np.maximum(acescct_decode(c), 0.0)
    y = lin @ _LUMA
    lin = y[..., None] + 0.92 * (lin - y[..., None])
    return acescct_encode(np.maximum(lin, 0.0))


LOOKS: Dict[str, Callable[[np.ndarray], np.ndarray]] = {
    "warm_print": warm_print,
    "broadcast_neutral": broadcast_neutral,
}
DESCRIPTIONS = {
    "warm_print": "warm print stock: warm balance, 1.08 contrast, highlight roll-off",
    "broadcast_neutral": "neutral broadcast trim: 0.92 saturation, 1.03 contrast",
}


def cube_text(name: str, fn: Callable[[np.ndarray], np.ndarray],
              size: int = SIZE) -> str:
    grid = np.arange(size, dtype=np.float64) / (size - 1)
    # .cube order: red fastest, then green, then blue.
    b, g, r = np.meshgrid(grid, grid, grid, indexing="ij")
    rgb = np.stack([r, g, b], axis=-1).reshape(-1, 3)
    out = np.clip(fn(rgb), 0.0, 1.0)
    lines = [
        f'TITLE "{name}"',
        f"# FlightSim show LUT {name}: {DESCRIPTIONS[name]}.",
        f"# Input and output: {SPACE} code values. Licence: {LICENCE}.",
        "# Generated by scripts/make_show_luts.py; do not edit by hand.",
        f"LUT_3D_SIZE {size}",
        "DOMAIN_MIN 0.0 0.0 0.0",
        "DOMAIN_MAX 1.0 1.0 1.0",
    ]
    # +0.0 folds -0.0 so the text never depends on a sign bit.
    lines += [f"{v[0] + 0.0:.6f} {v[1] + 0.0:.6f} {v[2] + 0.0:.6f}"
              for v in np.round(out, 6)]
    return "\n".join(lines) + "\n"


def generate(out: Path = OUT) -> Dict:
    out.mkdir(parents=True, exist_ok=True)
    entries = []
    for name, fn in LOOKS.items():
        text = cube_text(name, fn)
        path = out / f"{name}.cube"
        path.write_bytes(text.encode("utf-8"))
        entries.append({
            "name": name,
            "file": path.name,
            "sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
            "licence": LICENCE,
            "space": SPACE,
            "size": SIZE,
            "description": DESCRIPTIONS[name],
            "source": "generated by scripts/make_show_luts.py (project's own work)",
        })
    index = {"looks": entries}
    (out / "looks.json").write_bytes(
        (json.dumps(index, indent=1) + "\n").encode("utf-8"))
    return index


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args(argv)
    for entry in generate(args.out)["looks"]:
        print(f"{entry['file']}  {entry['sha256']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
