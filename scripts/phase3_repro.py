#!/usr/bin/env python3
"""Reproduce, diff, localize: the first move on any Phase 3 box failure.

    python scripts/phase3_repro.py A9            # write docs/phase3/packets/A9-repro.md
    python scripts/phase3_repro.py A9 --print    # also print it

Before any agent is asked to reason about a cause, this script lays out the
mechanical facts side by side: the box's verify line from the sheet, the
note's chosen approach and files, the last green run (commit and run id from
the state file and sync log), the current commit, the diff of the box's own
files between the two, and the newest failure packet's error text. The
debug triage reads this packet first; the "last green" diff is where most of
the last run's failures were visible at a glance (a path one level up, a
CRLF, a stale import, a relative cwd).

The runner records ``green_commit`` in the state file on every PASS so this
has something to diff against. Standard library only.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
P3 = ROOT / "docs" / "phase3"


def sh(*cmd: str) -> str:
    try:
        return subprocess.check_output(cmd, cwd=ROOT, text=True, stderr=subprocess.STDOUT).strip()
    except subprocess.CalledProcessError as exc:
        return f"(failed: {exc.output.strip()[:300]})"


def verify_line(box: str) -> str:
    txt = (ROOT / "tasks" / "phase3_checklist.md").read_text(encoding="utf-8")
    m = re.search(rf"^- \[( |x|X)\] \*\*{box} ·.*?(?=^- \[|^###|^##)", txt, re.S | re.M)
    if not m:
        return "(box not found on the sheet)"
    block = m.group(0)
    checks = re.findall(r"^\s+- Check: (.+)$", block, re.M)
    return "\n".join(checks) or block.strip()


def note_section(box: str, heading: str) -> str:
    p = P3 / "notes" / f"{box}.md"
    if not p.exists():
        return "(no note)"
    txt = p.read_text(encoding="utf-8")
    m = re.search(rf"^## {heading}\s*\n(.*?)(?=^## |\Z)", txt, re.S | re.M)
    return m.group(1).strip() if m else f"(no ## {heading} section)"


def note_files(box: str) -> list[str]:
    plan = note_section(box, "coding_plan") + "\n" + note_section(box, "steps")
    files = set(re.findall(r"\b((?:core|webapp|flightsim|scripts|tests|ue|assets|assets_pipeline|docs)/[\w./\-]+\.\w+)", plan))
    return sorted(f for f in files if "..." not in f)


def last_green(box: str, st: dict) -> tuple[str, str]:
    commit = st.get("green_commit") or ""
    run_id = st.get("green_run_id") or (st.get("run_id") if st.get("verdict") == "PASS" else "") or ""
    if not commit:
        # fall back to the sync log's last row for this box
        letter = box[0]
        p = P3 / f"sync_log_{letter}.md"
        if p.exists():
            rows = re.findall(rf"^\|\s*{box}\s*\|[^\n]*", p.read_text(encoding="utf-8"), re.M)
            if rows:
                m = re.search(r"\b([0-9a-f]{7,40})\b", rows[-1])
                commit = m.group(1) if m else ""
    return commit, run_id


def newest_packet(box: str) -> tuple[str, str]:
    ps = sorted(P3.glob(f"packets/{box}-[0-9]*.md"), key=lambda p: int(re.search(r"-(\d+)\.md$", p.name).group(1)))
    if not ps:
        return "", "(no failure packet)"
    txt = ps[-1].read_text(encoding="utf-8")
    m = re.search(r"(?is)(error|traceback|refused|FAIL)[^\n]*\n(?:.*\n){0,25}", txt)
    return ps[-1].name, (m.group(0).strip() if m else txt[:1500])


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    box = sys.argv[1].upper()
    st_path = P3 / "state" / f"{box}.json"
    st = json.loads(st_path.read_text(encoding="utf-8")) if st_path.exists() else {}
    head = sh("git", "rev-parse", "--short", "HEAD")
    green, green_run = last_green(box, st)
    files = note_files(box)
    diff_stat = sh("git", "diff", "--stat", f"{green}..HEAD", "--", *files) if green and files else "(no last green commit or no files in the note)"
    diff = sh("git", "diff", f"{green}..HEAD", "--", *files) if green and files else ""
    if len(diff) > 12000:
        diff = diff[:12000] + "\n... (truncated; full diff: git diff " + green + "..HEAD -- " + " ".join(files) + ")"
    pname, err = newest_packet(box)
    out = f"""# {box} repro packet

Generated by scripts/phase3_repro.py at HEAD {head}. Read this before reasoning about a cause.

## The sheet's check
{verify_line(box)}

## The note's chosen approach
{note_section(box, "approaches")[:1500]}

## Files the note names
{chr(10).join('- ' + f for f in files) or '(none found in the note)'}

## Last green
- commit: {green or '(none recorded; the runner writes green_commit on PASS)'}
- run id: {green_run or '(none)'}
- state verdict now: {st.get('verdict', '')!r}, failures: {len(st.get('failures', []) or [])}

## What changed in the box's files since last green
```
{diff_stat}
```
```diff
{diff}
```

## Newest failure packet ({pname or 'none'})
```
{err}
```

## First moves, in order
1. Re-run the box's own check exactly as the sheet says, with full output, on this machine.
2. If it fails the same way: is the cause in the diff above? A path, a line ending, a relative cwd, a stale artifact, a missing import after a re-convert? Fix that one thing.
3. If the diff is empty or innocent: is the machine the cause? Run scripts/windows_env_check.ps1 and compare docs/phase3/machine.json with the last green run's facts.
4. Only then ask for a new approach.
"""
    dest = P3 / "packets" / f"{box}-repro.md"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(out, encoding="utf-8")
    print(f"wrote {dest.relative_to(ROOT)}")
    if "--print" in sys.argv:
        print(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
